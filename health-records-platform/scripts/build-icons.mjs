// Extracts the Google Material Symbols (Rounded, weight 400) we actually use
// into a small TypeScript map of SVG paths. Shipping only these glyphs keeps
// pages light on slow connections — the full icon font is several megabytes.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const ICONS = [
  "home", "dashboard", "folder_open", "description", "upload_file", "cloud_upload", "timeline", "shield_person",
  "verified_user", "verified", "history", "notifications", "settings", "person", "badge", "logout", "login",
  "search", "filter_list", "tune", "sort", "download", "visibility", "visibility_off", "flag", "edit_note",
  "check", "check_circle", "close", "cancel", "block", "warning", "error", "info", "help", "schedule",
  "hourglass_top", "event", "calendar_month", "local_hospital", "domain", "apartment", "science", "medication",
  "radiology", "vaccines", "allergy", "stethoscope", "bed", "exit_to_app", "procedure", "clinical_notes",
  "diagnosis", "lab_profile", "lock", "lock_open", "key", "password", "devices", "keyboard_arrow_down", "mobile",
  "mail", "call", "arrow_forward", "arrow_back", "chevron_right", "chevron_left", "more_vert",
  "add", "remove", "group", "group_add", "person_add", "manage_accounts", "admin_panel_settings", "policy",
  "gavel", "report", "emergency", "emergency_home", "support_agent", "contact_support", "list_alt", "receipt_long",
  "fact_check", "rule", "task_alt", "pending", "pending_actions", "do_not_disturb_on", "share", "link_off",
  "person_search", "id_card", "fingerprint", "qr_code_2", "attach_file", "picture_as_pdf", "image", "monitoring",
  "analytics", "security", "health_and_safety", "privacy_tip", "account_circle", "menu", "refresh", "open_in_new",
  "content_copy", "mark_email_read", "sms", "wifi_off", "restart_alt", "draft", "send", "inbox", "pause_circle",
  "play_circle", "playlist_add_check", "clinical_notes", "medical_information", "contract", "how_to_reg",
  "person_off", "content_paste_search", "markunread_mailbox", "language", "location_on", "circle", "upload",
];

const dir = "node_modules/@material-symbols/svg-400/rounded";
const out = {};
const missing = [];
for (const name of [...new Set(ICONS)]) {
  const read = (f) => (existsSync(`${dir}/${f}.svg`) ? readFileSync(`${dir}/${f}.svg`, "utf8") : null);
  const outline = read(name);
  if (!outline) { missing.push(name); continue; }
  const fill = read(`${name}-fill`) ?? outline;
  const d = (svg) => [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(" ");
  out[name] = [d(outline), d(fill)];
}
if (missing.length) console.warn("Missing icons:", missing.join(", "));

const body = `// AUTO-GENERATED by scripts/build-icons.mjs — Google Material Symbols (Rounded, 400), Apache-2.0.
// Do not edit by hand; add names to the script and run \`npm run icons\`.
/* eslint-disable */
export const ICON_PATHS = ${JSON.stringify(out)} as const;
export type IconName = keyof typeof ICON_PATHS;
`;
writeFileSync("src/components/ui/icon-paths.ts", body);
console.log(`Wrote ${Object.keys(out).length} icons.`);
